#include <iostream>
#include <iomanip>
#include <cmath>

using namespace std; // Подключаем пространство имен std

int main() {
    // Настройка вывода для поддержки русского языка в консоли Windows
    setlocale(LC_ALL, "Russian");

    const double eps = 1e-4; // Заданная точность 10^-4
    double S = 0.0;          // Переменная для хранения суммы ряда
    double an = 1.0;         // Первый член ряда (при n=1: 1^3 / 0! = 1)
    double factorial = 1.0;  // Хранилище текущего значения факториала (3n-3)!
    int n = 1;               // Счетчик членов ряда

    

    while (an >= eps) {
        S += an; // Добавляем текущий член в общую сумму
        
        cout << "n = " << n << " | An = " << fixed << setprecision(6) 
             << an << " | Текущая сумма S = " << S << "\n";

        // Переходим к следующему шагу
        n++;

        // Вычисляем новый факториал (3n-3)! для следующего n
        factorial *= (3 * n - 5) * (3 * n - 4) * (3 * n - 3);

        // Вычисляем значение An для следующей итерации
        an = pow(n, 3) / factorial;
    }

    cout << "-----------------------------------------\n";
    cout << "Расчет окончен.\n";
    cout << "Итоговая сумма ряда S = " << setprecision(6) << S << "\n";
    cout << "Количество учтенных членов ряда: " << (n - 1) << "\n";

    return 0;
}